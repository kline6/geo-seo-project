const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM ai_tools ORDER BY id');
    res.json(result.rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM ai_tools WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.post('/', async (req, res) => {
  try {
    const Cols = req.body;
    const result = await pool.query(
      'INSERT INTO ai_tools (name, description, category, icon, color, popularity, uses, last_used) VALUES ($1, $2, $3, $4, $5, $6, $7, $8) RETURNING *',
      [Cols.name, Cols.description, Cols.category, Cols.icon, Cols.color, Cols.popularity, Cols.uses, Cols.last_used]
    );
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.put('/:id', async (req, res) => {
  try {
    const Cols = req.body;
    const result = await pool.query(
      'UPDATE ai_tools SET name=$1, description=$2, category=$3, icon=$4, color=$5, popularity=$6, uses=$7, last_used=$8 WHERE id=$9 RETURNING *',
      [Cols.name, Cols.description, Cols.category, Cols.icon, Cols.color, Cols.popularity, Cols.uses, Cols.last_used, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.delete('/:id', async (req, res) => {
  try {
    await pool.query('DELETE FROM ai_tools WHERE id = $1', [req.params.id]);
    res.json({ success: true });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

module.exports = router;
