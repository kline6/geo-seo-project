const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM seo_keywords ORDER BY id');
    res.json(result.rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM seo_keywords WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.post('/', async (req, res) => {
  try {
    const Cols = req.body;
    const result = await pool.query(
      'INSERT INTO seo_keywords (keyword, volume, visibility, position, prev_position, status, platform) VALUES ($1, $2, $3, $4, $5, $6, $7) RETURNING *',
      [Cols.keyword, Cols.volume, Cols.visibility, Cols.position, Cols.prev_position, Cols.status, Cols.platform]
    );
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.put('/:id', async (req, res) => {
  try {
    const Cols = req.body;
    const result = await pool.query(
      'UPDATE seo_keywords SET keyword=$1, volume=$2, visibility=$3, position=$4, prev_position=$5, status=$6, platform=$7 WHERE id=$8 RETURNING *',
      [Cols.keyword, Cols.volume, Cols.visibility, Cols.position, Cols.prev_position, Cols.status, Cols.platform, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.delete('/:id', async (req, res) => {
  try {
    await pool.query('DELETE FROM seo_keywords WHERE id = $1', [req.params.id]);
    res.json({ success: true });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

module.exports = router;
