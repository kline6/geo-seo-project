const express = require('express');
const router = express.Router();
const pool = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM keyword_tracking ORDER BY id');
    res.json(result.rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM keyword_tracking WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.post('/', async (req, res) => {
  try {
    const Cols = req.body;
    const result = await pool.query(
      'INSERT INTO keyword_tracking (keyword, target_url, google_rank, geo_visibility, search_volume, competition, cpc) VALUES ($1, $2, $3, $4, $5, $6, $7) RETURNING *',
      [Cols.keyword, Cols.target_url, Cols.google_rank, Cols.geo_visibility, Cols.search_volume, Cols.competition, Cols.cpc]
    );
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.put('/:id', async (req, res) => {
  try {
    const Cols = req.body;
    const result = await pool.query(
      'UPDATE keyword_tracking SET keyword=$1, target_url=$2, google_rank=$3, geo_visibility=$4, search_volume=$5, competition=$6, cpc=$7 WHERE id=$8 RETURNING *',
      [Cols.keyword, Cols.target_url, Cols.google_rank, Cols.geo_visibility, Cols.search_volume, Cols.competition, Cols.cpc, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.delete('/:id', async (req, res) => {
  try {
    await pool.query('DELETE FROM keyword_tracking WHERE id = $1', [req.params.id]);
    res.json({ success: true });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

module.exports = router;
